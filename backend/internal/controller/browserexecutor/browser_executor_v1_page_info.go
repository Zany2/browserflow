package browserexecutor

import (
	"context"

	"github.com/Zany2/browserflow/backend/api/browserexecutor/v1"
	"github.com/Zany2/browserflow/backend/utility/browserexecutor"
)

// BrowserExecutorPageInfo gets active page info. 获取当前页面信息。
func (c *ControllerV1) BrowserExecutorPageInfo(ctx context.Context, req *v1.BrowserExecutorPageInfoReq) (res *v1.BrowserExecutorPageInfoRes, err error) {
	executor, err := browserexecutor.Current(ctx)
	if err != nil {
		if failBrowserExecutor(ctx, nil, err) {
			return nil, nil
		}
		return nil, err
	}
	result, opErr := executor.PageInfo(ctx)
	if opErr != nil {
		if failBrowserExecutor(ctx, result, opErr) {
			return nil, nil
		}
		return nil, opErr
	}
	return &v1.BrowserExecutorPageInfoRes{Result: result}, nil
}
